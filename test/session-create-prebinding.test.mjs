import assert from 'node:assert/strict';
import test from 'node:test';

import { askInWorkspaceSession } from '../src/channels/shared/workspace-session.mjs';

/** A State store that keeps bindings in memory, like the real one. */
function memoryState() {
  const bindings = new Map();
  return {
    sessionFor: (key) => bindings.get(key) ?? null,
    setSession: async (key, id) => { bindings.set(key, id); return true; },
    clearSession: async (key) => { bindings.delete(key); },
  };
}

test('the conversation owns the session id before that session is created', async () => {
  const state = memoryState();
  const seen = {};
  const harness = {
    canChooseSessionId: true,
    createSession: async (options) => {
      // Prompt assembly happens inside this call, so the binding must already be
      // visible to whoever resolves the conversation by session id.
      seen.requested = options.sessionId;
      seen.boundDuringCreate = state.sessionFor('direct:chat');
      return options.sessionId;
    },
    ask: async () => 'answer',
    sessionExists: async () => true,
    conversationWorkspaceGeneration: () => null,
  };
  await askInWorkspaceSession({ harness, state, key: 'direct:chat', text: 'hello' });
  assert.match(seen.requested ?? '', /^session-[0-9a-f-]{36}$/u, 'the id is generated by the caller');
  assert.equal(seen.boundDuringCreate, seen.requested, 'the binding exists before creation');
  assert.equal(state.sessionFor('direct:chat'), seen.requested);
});

test('a Harness that cannot choose the id keeps the old order', async () => {
  const state = memoryState();
  let boundDuringCreate = 'unset';
  const harness = {
    createSession: async () => {
      boundDuringCreate = state.sessionFor('direct:chat');
      return 'generated-session';
    },
    ask: async () => 'answer',
    sessionExists: async () => true,
    conversationWorkspaceGeneration: () => null,
  };
  await askInWorkspaceSession({ harness, state, key: 'direct:chat', text: 'hello' });
  assert.equal(boundDuringCreate, null, 'nothing is bound until the Harness answers');
  assert.equal(state.sessionFor('direct:chat'), 'generated-session');
});

test('a failed creation leaves the previous binding untouched', async () => {
  const state = memoryState();
  await state.setSession('direct:chat', 'old-session');
  const harness = {
    canChooseSessionId: true,
    createSession: async () => { throw new Error('boom'); },
    ask: async () => 'answer',
    // The recorded session is gone, so the flow tries to replace it and fails.
    sessionExists: async () => false,
    conversationWorkspaceGeneration: () => null,
  };
  await assert.rejects(askInWorkspaceSession({ harness, state, key: 'direct:chat', text: 'hello' }), /boom/u);
  assert.equal(state.sessionFor('direct:chat'), 'old-session');
});
